def _build(meta):
    rng = random.Random(meta["seed"])
    months = meta["months"]
    returns = []
    for m in months:
        row = {}
        for a in IDS:
            noise = rng.uniform(-0.015, 0.015) * (0.3 if a == "bond" else 1)
            row[a] = round(m["base"][a] + noise, 4)
        returns.append(row)
    prices = {}
    for a in ASSETS:
        p = [a["price"]]
        for r in returns:
            p.append(p[-1] * (1 + r[a["id"]]))
        prices[a["id"]] = p
    bench = [START_CASH]
    for t in range(1, len(months) + 1):
        bench.append(sum(START_CASH / len(IDS) * prices[a][t] / prices[a][0] for a in IDS))
    return {**meta, "returns": returns, "prices": prices, "bench": bench}
